/**
 * 设置组的提示文案（v0.26 抽出）——从旧前端 `components/settings/groupTips.ts` 搬来。
 *
 * 抽出来的理由很直接：同一个组现在有**两个宿主**——总设置弹窗，以及它所属的
 * 模块页（长期记忆在记忆页、联网与沙箱在能力页）。写在两处就一定会分叉，
 * 而"同一条设置在两个地方说法不一样"比没有说明更糟。
 *
 * 2026-09-24（用户第二轮反馈）：这里原先写的是"这一组是干什么的"，那是**解释**——
 * 用户原话"不需要你解释这是个什么东西"。现在只留两类：
 * - **填这一格需要的**：密钥怎么算改、留空什么意思、清单语法怎么写；
 * - **动手前必须知道的代价**：沙箱是权限最大的动作、开深度思考更慢更费。
 * 机制类的整段（记忆两路怎么生效、ReMe 跑在哪儿、抓网页的访问范围）已删除。
 */

/** 浏览态：这一格的**填法或代价**（挂在标题后面那个问号上）；纯解释的不写。 */
export function groupTip(key: string): string {
  const tips: Record<string, string> = {
    web: '搜索需要一个服务商密钥（Tavily / 博查）；抓网页不需要密钥。',
    sandbox: '默认「先问」：这是权限最大的一个动作。',
  }
  return tips[key] ?? ''
}

/** 编辑态：改这一组之前该知道的一件事（同样是"填法/代价"，不是"它是什么"）。 */
export function editHint(key: string): string {
  const hints: Record<string, string> = {
    llm: '打开会更慢、更费 token；关掉更快，但难题上的推导会浅一些。',
    web: '密钥只回显掩码。留空表示不改动；要清掉它请用下方「清除」入口。',
    sandbox: '三张清单的语法照抄 Claude Code：Bash(git status:*) 这样写，拒绝优先于放行。',
  }
  return hints[key] ?? ''
}
