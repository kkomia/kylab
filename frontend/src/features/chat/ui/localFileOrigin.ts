/**
 * 「来源服务器（文件未随导入）」——导入过来的产物与附件**如实标出**（M2 阶段 6）。
 *
 * ## 为什么是一句 `title` 而不是卡片上的一块标
 *
 * 判据本该落在"这份文件的来源"上，而**契约里没有这个字段**：
 * `ConversationArtifactOut`（`/conversations/{id}/artifacts`）与 `describe()` 给的
 * 是 `storage` / `where` / `path`（工作区那份才有 `path`），`location` 不在响应里——
 * 而 `location` 恰恰是唯一的判据（导入过来的那些保着 NAS 上的 key，§3.1 R4）。
 * 阶段 5 已经登记过"这三笔账不进服务器档 OpenAPI"，同一条理由在这里再成立一次：
 * **不为界面上一句话去动契约**（那是 M3 导入向导/提供者那一批的事）。
 *
 * 所以按施工口径的兜底办：**放在卡片与附件的 `title` 上**（悬停即见、一个字不丢），
 * 而不是在卡片上另加一块"可能对、也可能不对"的标——界面上摆一句不成立于所有卡片的
 * 话，比不摆更糟。
 *
 * ## 这句话对**每**一份产物都成立吗（能，因为它是条件句）
 *
 * - 导入过来的：`storage` 是 NAS 上的那份（`object` 或 `workspace`），本机只有引用，
 *   点预览/下载会打在**本机对象存储**上，取不到 → 这句话就是它；
 * - 本机新产出的：文件在本机（工作区目录或本机对象存储）→ 这句话的后半句替它说话。
 *
 * 两半都写全，是因为这句话唯一可能出现的地方就是"用户想知道这份文件到底在哪"，
 * 而那时只讲一半会把人带偏（"是不是我这台机器上也没有？"）。
 */

/** 卡片与附件共用的那一句（**同一处措辞**：两处各写一份，迟早会长出两个版本）。 */
export const FILE_ORIGIN_HINT =
  '来源服务器（文件未随导入）：从旧服务器导进来的产物/附件只有引用，' +
  '文件本体还在那台服务器上；本机新产出的文件在本机，能直接预览与下载'

/** 给一个名字配上面那句（`title` 要带上名字：同名几份时悬停才分得清）。 */
export function titledWithOrigin(name: string): string {
  return `${name}\n${FILE_ORIGIN_HINT}`
}
